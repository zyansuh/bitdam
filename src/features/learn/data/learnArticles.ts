import type { LearnArticle } from '../types/learn'

function article(
  slug: string,
  category: LearnArticle['category'],
  title: string,
  lead: string,
  sections: LearnArticle['sections'],
  featured = false,
): LearnArticle {
  const words = sections.reduce((sum, section) => sum + section.paragraphs.join('').length, 0)
  return {
    slug,
    category,
    title,
    question: title,
    lead,
    minutes: Math.max(3, Math.round(words / 420)),
    featured,
    sections,
  }
}

